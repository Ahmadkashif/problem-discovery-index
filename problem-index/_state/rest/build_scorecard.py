"""Write _scorecard-index-rest.md from _state/rest/qualifiers.jsonl and scorecard_overlaps.md. Coordinator only.

Each qualifiers.jsonl line: {"path": "niches/<slug>/<dir>", "name", "industry", "fn", "q": [q1..q5], "batch", "case"}.
The score is computed from q; the table is re-ranked by score, then Q1, Q3, name. The scorecards themselves live
in each profile, so the script also checks that every path's profile still says Qualified with the same total.
Usage (vault root): python3 _state/rest/build_scorecard.py
"""
import json, re, sys

W = (3, 2, 3, 2, 2)
rows = [json.loads(l) for l in open("_state/rest/qualifiers.jsonl") if l.strip()]
bad = []
for r in rows:
    r["score"] = sum(w * q for w, q in zip(W, r["q"]))
    t = open(r["path"] + "/profile.md").read()
    m = re.search(r"\*\*(\d+)/60\*\*", t)
    if "Qualified" not in t or not m or int(m.group(1)) != r["score"]:
        bad.append(f"MISMATCH {r['path']} profile={m and m.group(1)} index={r['score']}")
if bad:
    sys.exit("\n".join(bad))
rows.sort(key=lambda r: (-r["score"], -r["q"][0], -r["q"][2], r["name"]))
out = ["# Scorecard Index — Remaining Industries", "",
       "Qualifying Pass 2 pockets (**≥50/60, no live kill switch**) from the industries built under "
       "`_remaining-industry-implementation-and-discovery-plan.md`. Kept separate from `_scorecard-index.md` "
       "until the Stage E merge (plan §10). Generated by `_state/rest/build_scorecard.py`; edit "
       "`_state/rest/qualifiers.jsonl`, not this file.", "",
       "**Rubric:** Q1 Insight is the invoice (×3) · Q2 Labour mass + repeatable (×2) · Q3 Proprietary data moat (×3) "
       "· Q4 External clock (×2) · Q5 Buyer + market (×2), max 60. Method: `_direction.md`.", "", "---", "",
       "## Ranked", "",
       "| # | Pocket | Industry | Insight Fn | Q1 | Q2 | Q3 | Q4 | Q5 | Score |",
       "|---|---|---|---|---|---|---|---|---|---|"]
for i, r in enumerate(rows, 1):
    q = " | ".join(str(x) for x in r["q"])
    out.append(f"| {i} | [[{r['path']}/profile\\|{r['name']}]] | {r['industry']} | {r['fn']} | {q} | **{r['score']}** |")
out += ["", "## Cases", ""]
for i, r in enumerate(rows, 1):
    out += [f"**{i}. {r['name']} ({r['score']}).** {r['case']} *(batch {r['batch']})*", ""]
out += [open("_state/rest/scorecard_overlaps.md").read().rstrip(), ""]
open("_scorecard-index-rest.md", "w").write("\n".join(out))
print(f"{len(rows)} qualifiers written to _scorecard-index-rest.md")
